"""The plan/price table, and the ONE source it comes from.

`guardian_hub.plans` is that source. This module asserts the five
subscriptions and their two intervals against it from every direction they
reach a customer:

* the catalogue's own invariants (five plans, two intervals, integer cents,
  twelve-for-ten yearly);
* the hub payload the in-app Billing page renders;
* and -- the one that actually protects revenue -- the prices hard-coded in
  `site/index.html`, which is a separate static artifact no Python import can
  keep honest. A wrong number there is a wrong number a stranger reads before
  they ever have an account, so it is parsed out of the HTML and compared
  against the catalogue.

Nine copies of that markup exist now, not one: `site/index.html` (English)
plus the eight locale files `site/<locale>/index.html` generated by
`site/i18n/build_locales.py`. Prices are never translated -- they stay in US
dollars and the same `data-plan`/`data-interval` attributes in every
language -- but a generator bug could still drop a card or a digit in one
locale and not the others, and that would be invisible to a test that only
ever reads the English file. So this module checks all nine.
"""

import pathlib
import re

import pytest

from guardian_hub import plans
from guardian_hub.config import settings
from tests.test_auth import login, seed_user

SITE_DIR = pathlib.Path(__file__).resolve().parents[2] / "site"
SITE_HTML = SITE_DIR / "index.html"

# Every locale build_locales.py generates, plus "" for the English root --
# kept as a plain literal rather than imported from build_locales.LOCALES so
# this test still fails loudly (unknown locale directory / missing locale)
# if that script's list and the actual generated directories ever disagree.
SITE_LOCALES = ["", "ar", "es", "fr", "de", "pt", "it", "zh", "hi"]

# The plan table as the owner stated it, written out longhand rather than
# derived from `plans` -- a test that computes its expectation from the code
# under test proves only that the code agrees with itself.
EXPECTED = {
    "trial":               (0,      0,      False),
    "home":                (900,    9000,   False),
    "business_essentials": (4900,   49000,  True),
    "business_pro":        (14900,  149000, False),
    "partner":             (9900,   99000,  True),
}


def test_five_plans_two_intervals_and_the_stated_prices():
    assert len(plans.PLANS) == 5
    assert set(plans.BY_ID) == set(EXPECTED)
    assert plans.INTERVALS == ("month", "year")
    for pid, (monthly, yearly, per_site) in EXPECTED.items():
        p = plans.BY_ID[pid]
        assert isinstance(p.monthly_cents, int) and isinstance(p.yearly_cents, int)
        assert not isinstance(p.monthly_cents, bool)
        assert p.monthly_cents == monthly, pid
        assert p.yearly_cents == yearly, pid
        assert p.per_site is per_site, pid
        assert p.cents("month") == monthly and p.cents("year") == yearly


def test_the_trial_is_its_own_subscription_and_is_free():
    assert plans.TRIAL.is_trial is True
    assert plans.TRIAL.id in plans.BY_ID
    assert plans.TRIAL not in plans.PAID_PLANS
    assert len(plans.PAID_PLANS) == 4
    assert plans.TRIAL.cents("month") == plans.TRIAL.cents("year") == 0
    assert plans.TRIAL_DAYS == 90
    # Not purchasable through Stripe: no paid plan is free, so a zero price
    # can only ever be the trial.
    assert all(p.monthly_cents > 0 for p in plans.PAID_PLANS)


def test_yearly_is_twelve_months_for_the_price_of_ten():
    assert plans.YEARLY_MONTHS_CHARGED == 10
    for p in plans.PAID_PLANS:
        assert p.yearly_cents == p.monthly_cents * 10, p.id
        # The saving the toggle advertises: two months, i.e. 1/6th off.
        assert p.monthly_cents * 12 - p.yearly_cents == p.monthly_cents * 2


def test_lookup_keys_are_stable_and_unique():
    keys = [p.lookup_key(i) for p in plans.PAID_PLANS for i in plans.INTERVALS]
    assert len(set(keys)) == 8
    assert "guardian_business_essentials_year" in keys
    # The webhook maps a Stripe price back to a plan by splitting this key --
    # so no plan id may end in "_month"/"_year" or contain the separator in a
    # way that makes the split ambiguous.
    for p in plans.PLANS:
        assert not p.id.endswith(("_month", "_year"))


def test_price_labels_are_what_a_customer_reads():
    assert plans.price_label(plans.BY_ID["home"], "month") == "$9/mo"
    assert plans.price_label(plans.BY_ID["home"], "year") == "$90/yr"
    assert plans.price_label(plans.BY_ID["business_essentials"], "month") == "$49/site/mo"
    assert plans.price_label(plans.BY_ID["partner"], "year") == "$990/site/yr"
    assert plans.price_label(plans.BY_ID["business_pro"], "year") == "$1490/yr"
    assert plans.price_label(plans.TRIAL, "month") == "Free"


def test_the_api_payload_carries_both_intervals_from_the_catalogue(client, monkeypatch):
    # This test is about the catalogue path, so it pins the mode that offers
    # it. The hub's default is "trial_only" (one card) -- asserted separately
    # in `test_billing_trial_only.py`.
    monkeypatch.setattr(settings, "billing_mode", "plans")
    seed_user(); login(client)
    body = client.get("/api/v1/billing").json()
    assert body["currency"] == plans.CURRENCY
    assert body["trial_days"] == plans.TRIAL_DAYS
    assert body["yearly_months_charged"] == plans.YEARLY_MONTHS_CHARGED
    cards = {c["id"]: c for c in body["plans"]}
    assert set(cards) == set(EXPECTED)
    for pid, (monthly, yearly, per_site) in EXPECTED.items():
        assert cards[pid]["monthly_cents"] == monthly
        assert cards[pid]["yearly_cents"] == yearly
        assert cards[pid]["per_site"] is per_site
        assert cards[pid]["monthly_label"] == plans.price_label(plans.BY_ID[pid], "month")
        assert cards[pid]["yearly_label"] == plans.price_label(plans.BY_ID[pid], "year")
    assert cards["trial"]["is_trial"] is True


