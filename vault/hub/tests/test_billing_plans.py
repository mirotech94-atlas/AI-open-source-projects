def _pricing_section(locale: str = "") -> str:
    path = SITE_DIR / locale / "index.html" if locale else SITE_HTML
    html = path.read_text(encoding="utf-8")
    section = re.search(r'<section id="pricing".*?</section>', html, re.S)
    assert section, f"{path} has no #pricing section"
    return section.group(0)


#: Every price the catalogue can render, in the exact form the old tier cards
#: printed them. None of these may appear on the public site while the product
#: offers the trial only -- the reason this test exists is that a stale price
#: left in one locale is invisible to a test that only reads the English file.
FORBIDDEN_PRICES = sorted(
    {plans.price_label(p, i) for p in plans.PAID_PLANS for i in plans.INTERVALS}
    | {f"${p.cents(i) // 100}" for p in plans.PAID_PLANS for i in plans.INTERVALS}
)


@pytest.mark.parametrize("locale", SITE_LOCALES)
def test_the_public_site_quotes_no_price_while_the_product_is_trial_only(locale):
    """The site offers the free trial and nothing else, in every language.

    The catalogue in `plans.py` is deliberately still complete -- switching
    `billing_mode` back to "plans" is a setting, not a rewrite -- so the thing
    that has to hold here is the *absence* of those prices from the public
    HTML, in all nine files. The English file is hand-edited and the eight
    locales are generated from it by `site/i18n/build_locales.py`; a generator
    bug that left one locale's tier grid behind would show up here and nowhere
    else.
    """
    path = SITE_DIR / locale / "index.html" if locale else SITE_HTML
    html = path.read_text(encoding="utf-8")
    where = f"site/{locale}/index.html" if locale else "site/index.html"

    for price in FORBIDDEN_PRICES:
        assert price not in html, f"{where}: still quotes {price}"
    # The machinery of a tier grid, not just the digits: a card, the
    # month/year toggle, or a checkout link is equally a plan on offer.
    for marker in ('data-plan="', 'data-interval="', "interval-toggle", "/settings/billing?plan="):
        assert marker not in html, f"{where}: still carries {marker!r}"

    section = _pricing_section(locale)
    assert "<article" not in section, f"{where}: the pricing section still has cards"
    # It still has to say what IS on offer -- an empty section would pass
    # every assertion above. Either destination counts: the call to action
    # used to scroll to #access because the sign-up form was embedded there,
    # and now that the form has its own page it links straight to it. What
    # this guards is that the section still sends the reader somewhere.
    assert ('href="#access"' in section or 'href="/signup.html"' in section), \
        f"{where}: pricing section has no call to action"


def test_the_catalogue_is_kept_whole_for_the_day_plans_come_back():
    # The site quoting nothing must not quietly become the catalogue being
    # emptied: flipping `billing_mode` to "plans" has to bring back real
    # prices, not blanks.
    assert len(plans.PAID_PLANS) == 4
    assert all(p.monthly_cents > 0 and p.yearly_cents > 0 for p in plans.PAID_PLANS)
