async def _gate(caption=CAPTION, *, series=True, captions=True, seconds=None):
    return await quality.check_file("/x.mp4", caption, series=series,
                                    seconds=seconds or quality.band(series),
                                    captions=captions)


async def test_a_good_series_episode_passes(file_is):
    info, why = await _gate()
    assert why is None and info["video_seconds"] == 72.0


