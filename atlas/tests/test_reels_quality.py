# ------------------------------------------------------------ the bands

def test_the_bands_are_the_owners_and_every_drafted_length_fits_them():
    """A correctly made reel must pass, or a remake is doomed: every beat
    count `beat_range` can draft sits inside its band."""
    assert quality.SERIES_SECONDS == (60.0, 90.0)
    assert quality.OTHER_SECONDS == (30.0, 60.0)
    for beats, band in ((playbook.SERIES_BEATS, quality.SERIES_SECONDS),
                        (playbook.OTHER_BEATS, quality.OTHER_SECONDS)):
        for n in range(beats[0], beats[1] + 1):
            assert band[0] <= n * veo.CLIP_SECONDS <= band[1], (n, band)


@pytest.mark.parametrize("package", ["stories", "business"])
def test_every_calendar_job_planned_length_passes_its_own_band(package):
    """The package, not the drafting rule, sets a calendar reel's length
    (FOOD reels are 12-35 s by design). A correct render passes; a render
    missing a whole clip does not."""
    for j in cal.jobs(package):
        planned = sum(p.length for p in cal.plan(j))
        low, high = quality.calendar_band(j)
        assert low <= planned <= high, j["job_id"]
        assert not low <= planned - veo.CLIP_SECONDS <= high, j["job_id"]


# ----------------------------------------------------------- the probe

def test_the_probe_reads_rotation_stream_length_and_subtitles():
    out = json.dumps({"format": {"duration": "72.1"}, "streams": [
        {"codec_type": "video", "width": 1920, "height": 1080, "duration": "8.0",
         "side_data_list": [{"rotation": -90}]},
        {"codec_type": "audio"}, {"codec_type": "subtitle"}]}).encode()
    info = ffmpeg.parse_probe(out)
    assert info["rotation"] == 270 and info["video_seconds"] == 8.0
    assert info["seconds"] == 72.1 and info["subtitles"] and info["audio"]
    tagged = json.dumps({"format": {}, "streams": [
        {"codec_type": "video", "width": 1080, "height": 1920,
         "tags": {"rotate": "180"}}]}).encode()
    assert ffmpeg.parse_probe(tagged)["rotation"] == 180
    assert ffmpeg.parse_probe(b'{"streams": []}')["video"] is False


needs_ffmpeg = pytest.mark.skipif(
    shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None,
    reason="ffmpeg not installed")


def _make(path, *, size="1080x1920", seconds=2, audio="sine=frequency=440"):
    argv = ["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i",
            f"color=c=black:s={size}:d={seconds}:r=10"]
    if audio:
        argv += ["-f", "lavfi", "-i", f"{audio}:duration={seconds}"]
    argv += ["-c:v", "libx264", "-pix_fmt", "yuv420p", "-preset", "ultrafast"]
    argv += ["-c:a", "aac", "-shortest"] if audio else ["-an"]
    subprocess.run([*argv, str(path)], check=True, timeout=60)


@needs_ffmpeg
async def test_real_tiny_files_through_the_real_probe(tmp_path):
    good = tmp_path / "good.mp4"
    _make(good)
    band = (1.0, 3.0)
    info, why = await quality.check_file(str(good), CAPTION, series=False,
                                         seconds=band)
    assert why is None, why
    assert (info["width"], info["height"]) == (1080, 1920)

    wide = tmp_path / "wide.mp4"
    _make(wide, size="1920x1080")
    _, why = await quality.check_file(str(wide), CAPTION, series=False, seconds=band)
    assert "1920x1080" in why

    mute = tmp_path / "mute.mp4"
    _make(mute, audio=None)
    _, why = await quality.check_file(str(mute), CAPTION, series=False, seconds=band)
    assert "no sound" in why

    quiet = tmp_path / "quiet.mp4"
    _make(quiet, audio="anullsrc=r=44100:cl=mono")
    _, why = await quality.check_file(str(quiet), CAPTION, series=False, seconds=band)
    assert "silent" in why

    _, why = await quality.check_file(str(good), CAPTION, series=True,
                                      seconds=quality.SERIES_SECONDS, captions=True)
    assert "plays 2.0 s" in why


