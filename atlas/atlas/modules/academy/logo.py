def tile(dark: bool, *, edge_px: float = EDGE_PX, scaling: bool = False,
         alpha: float | None = None, video: bool = False) -> str:
    """The mark's three shapes in its 64-unit space. `alpha` fades the tile's
    "A" (the watermark); the "0" always stays at full strength. `video`:
    the video system's colours (VIDEO_COLOURS) in place of the store's."""
    t, letter, zero, edge_c = VIDEO_COLOURS if video else COLOURS
    edge = _edge(edge_px, scaling, edge_c) if dark else ""
    a = f'<path d="{A_PATH}" fill="{letter}"/>'
    if alpha is not None:
        a = f'<g opacity="{alpha:g}">{a}</g>'
    return (f'{TILE_RECT} fill="{t}"{edge}/>{a}'
            f'<path d="{ZERO_PATH}" fill="{zero}"/>')


def mark_svg(dark: bool = True, *, inline: bool = False) -> str:
    """The 64x64 mark. `dark`: with its edge, for dark grounds. `inline`: for
    a page, sized by CSS and hidden from screen readers (the link names it)."""
    if inline:
        return (f'<svg viewBox="0 0 64 64" aria-hidden="true" focusable="false">'
                f'{tile(dark)}</svg>')
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" '
            'height="64" role="img"><title>ATLAS Academy</title>'
            f'{tile(dark)}</svg>\n')


def lockup_svg(dark: bool = False) -> str:
    """The mark, the wordmark and its line, as the source lays them out."""
    words = WORDS_DARK if dark else WORDS_LIGHT
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {LOCKUP_W:g} 64" '
            f'width="{LOCKUP_W:g}" height="64" role="img"><title>ATLAS Academy</title>'
            f'{tile(dark)}<path d="{WORD_PATH}" fill="{words}"/>'
            f'<path d="{TAG_PATH}" fill="{words}"/></svg>\n')


def icon_svg(size: int, *, fill: float = 0.78) -> str:
    """A square app icon: the mark (edged) on the black field, the tile
    `fill` of the side, so a circle crop never cuts it (YouTube, Android).
    The edge scales with the size so it still reads once shown small."""
    s = size * fill / 58                       # the tile is 58 of the mark's units
    off = (size - 58 * s) / 2 - 3 * s
    edge = max(EDGE_PX, size / 110) / s        # in mark units
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" '
            f'width="{size}" height="{size}"><rect width="{size}" height="{size}" '
            f'fill="{TILE}"/><g transform="translate({off:.3f} {off:.3f}) scale({s:.5f})">'
            f'{tile(True, edge_px=round(edge, 3), scaling=True)}</g></svg>\n')


# The tutorial watermark: the mark over the wordmark, 104x64 on the 1080p
# frame (tutorial_design.WATERMARK_XY sets it in the rail, inside safe-16-9).
WATERMARK_W, WATERMARK_H = 104, 64
WATERMARK_MARK = 46                  # the mark's side
WATERMARK_ALPHA = 0.62               # the "A" and the words; tutorial_design reads it


def watermark_svg(video: bool = False) -> str:
    """The edged tile at full strength (it sits on the rail), the "A" and
    the words at WATERMARK_ALPHA, the "0" full like the old blue rule.
    `video`: navy and the video blue (watermark-video.svg), the colours the
    video frame uses since 2026-10-17; without it, the 10-16 file."""
    letter = VIDEO_LETTER if video else LETTER
    ground = ("It always lands on navy: the rail is solid navy on every slide."
              if video else "It always lands on black: the rail is black on the scrim\n"
              "       slides and solid black beside the raised working sheet.")
    m = WATERMARK_MARK / 64
    mx = (WATERMARK_W - WATERMARK_MARK) / 2
    ws = WATERMARK_W / (WORD_X1 - WORD_X0)
    wy = WATERMARK_H - (WORD_Y1 - WORD_Y0) * ws - WORD_Y0 * ws
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{WATERMARK_W}" '
            f'height="{WATERMARK_H}" viewBox="0 0 {WATERMARK_W} {WATERMARK_H}">\n'
            '  <!-- The ATLAS Academy watermark (Grid A0, the owner 2026-10-16), built by\n'
            '       tools/academy_logo.py from atlas/modules/academy/logo.py; do not\n'
            '       edit by hand. The opacity is baked in, so ffmpeg overlays it as\n'
            f'       is. {ground} -->\n'
            f'  <g transform="translate({mx:g} -1.5) scale({m:g})">'
            f'{tile(True, alpha=WATERMARK_ALPHA, video=video)}</g>\n'
            f'  <g opacity="{WATERMARK_ALPHA:g}" transform="translate({-WORD_X0 * ws:.3f} '
            f'{wy:.3f}) scale({ws:.5f})"><path d="{WORD_PATH}" fill="{letter}"/></g>\n'
            '</svg>\n')
