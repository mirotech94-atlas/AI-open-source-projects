"""The week, in plain words.

The daily brief is a status report: sections, counts, check names. That is
right for something read every morning at the same time with the same shape.
A weekly summary read once is a different job — it should answer "what
happened, and what do I need to do about it" in the language someone would
use out loud.

So this deliberately does NOT reuse the brief's renderer. It counts and
consequences: "FlyCheap was fine all week" rather than eleven check names,
and "no backups exist, and that has been true for seven days" rather than
`cloudco.protection: failing`. Same discipline as the phone greeting — a thing
read once cannot be skimmed for the important line, so the important line has
to be the one that is said.

Nothing here is generated by a model. The numbers come from the same tables
the tiles read, and the sentences are assembled from them. A weekly summary
that quietly invented a figure would be worse than no weekly summary, and it
would take weeks to notice.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import UTC, datetime, timedelta
from typing import Any

from .contracts import Health, Severity

log = logging.getLogger("atlas.weekly")


@dataclass(frozen=True, slots=True)
class Weekly:
    at: datetime
    since: datetime
    headline: str
    paragraphs: list[str] = field(default_factory=list)

    def render(self) -> str:
        return "\n\n".join([f"*This week* — {self.window()}", self.headline,
                            *self.paragraphs])

    def window(self) -> str:
        """The exact reporting window, with its timezone: "20 to 27
        September" did not say whether either end was included."""
        a, b = self.since.astimezone(), self.at.astimezone()
        days = round((b - a).total_seconds() / 86400)
        return (f"the {days} days from {a:%a %-d %b %H:%M} to "
                f"{b:%a %-d %b %H:%M} {b:%Z}")


def _plural(n: int, one: str, many: str | None = None) -> str:
    return one if n == 1 else (many or one + "s")


async def build(days: int = 7, money: Any = None) -> Weekly:
    """Assemble the week from what was actually recorded. `money` is the
    reels Analyst's and Improver's week (`reel_money.week`), which `send`
    runs; without it the section reads the table fresh and decides nothing."""
    from .state import fetch_all

    now = datetime.now(UTC)
    since = now - timedelta(days=days)
    paragraphs: list[str] = []

    # --- what broke, and whether it is still broken --------------------
    still_wrong: list[tuple[str, str, str]] = []
    try:
        rows = await fetch_all(
            """SELECT DISTINCT ON (o.check_id)
                      o.health, o.detail, c.name AS check_name,
                      p.name AS property
                 FROM observations o
                 JOIN checks c ON c.id = o.check_id
                 JOIN properties p ON p.id = c.property_id
                ORDER BY o.check_id, o.at DESC""")
        for row in rows:
            if str(row["health"]) in (Health.FAILING, Health.DEGRADED):
                still_wrong.append((str(row["property"]),
                                    str(row["check_name"]),
                                    str(row["detail"] or "")))
    except Exception as exc:                            # noqa: BLE001
        log.warning("weekly: could not read the board: %s", exc)
        paragraphs.append(
            "I could not read my own records this week, so everything below "
            "is missing rather than empty. That is worth more attention than "
            "anything it would have said.")
        return Weekly(at=now, since=since,
                      headline="I can't tell you how the week went.",
                      paragraphs=paragraphs)

    # --- how long has each one been wrong? -----------------------------
    ongoing: list[str] = []
    for prop, check, detail in still_wrong:
        days_bad = None
        try:
            row = await fetch_all(
                """SELECT min(o.at) AS since
                     FROM observations o
                     JOIN checks c ON c.id = o.check_id
                     JOIN properties p ON p.id = c.property_id
                    WHERE p.name = $1 AND c.name = $2
                      AND o.health IN ('failing', 'degraded')
                      AND o.at > $3""", prop, check, since)
            if row and row[0]["since"]:
                days_bad = (now - row[0]["since"]).days
        except Exception:                               # noqa: BLE001
            log.debug("weekly: could not date %s %s; said without a length",
                      prop, check)
        how_long = (", and it has been like that all week" if days_bad
                    and days_bad >= days - 1 else
                    f", for {days_bad} {_plural(days_bad, 'day')}"
                    if days_bad else "")
        ongoing.append(f"• {detail or f'{prop} {check}'}{how_long}")

    if ongoing:
        paragraphs.append("*Still wrong right now*\n" + "\n".join(ongoing))

    # --- what is paused, waiting for his resume (R09 sets some) ---------
    try:
        from .pause import lines as paused
        held = await paused()
    except Exception:                                   # noqa: BLE001
        log.debug("weekly: pauses unreadable; said without them")
        held = []
    if held:
        paragraphs.append("*Paused until you resume*\n"
                          + "\n".join(f"• {line}" for line in held))

    # --- what ATLAS did, if anything -----------------------------------
    try:
        # actions_log is the hash-chained audit trail, not a table of
        # actions: the columns are `event` and `subject`, and the action
        # name is the subject. Querying a column called `action` failed
        # silently and the section simply did not appear -- which read as
        # "ATLAS did nothing", the same sentence watch-only produces, so
        # the bug was invisible in the output.
        acted = await fetch_all(
            """SELECT subject AS action, count(*) AS n
                 FROM actions_log
                WHERE at > $1 AND event = 'execute.start'
                GROUP BY subject ORDER BY n DESC""", since)
        if acted:
            lines = [f"• {r['action']} — {r['n']} {_plural(r['n'], 'time')}"
                     for r in acted]
            paragraphs.append("*What I did*\n" + "\n".join(lines))
        else:
            from .executor import watch_only
            paragraphs.append(
                "*What I did*\nNothing — "
                + ("I am in watch-only mode, so I report and don't act."
                   if watch_only() else
                   "nothing needed doing that I'm allowed to do."))
    except Exception as exc:                            # noqa: BLE001
        log.warning("weekly: could not read the action log: %s", exc)
        paragraphs.append(
            "*What I did*\nI could not read my own action log, so I cannot "
            "tell you. That is not the same as having done nothing.")

    # --- what is waiting on him ----------------------------------------
    try:
        pending = await fetch_all(
            "SELECT count(*) AS n FROM proposals WHERE status = 'pending'")
        waiting = int(pending[0]["n"]) if pending else 0
        if waiting:
            paragraphs.append(
                f"*Waiting on you*\n{waiting} "
                f"{_plural(waiting, 'decision')} I can't make. They expire "
                f"on their own if you'd rather they didn't happen.")
    except Exception:                                   # noqa: BLE001
        log.warning("weekly: could not count proposals")

    # --- approvals that came back (S08/P04): say why a card reappeared ---
    try:
        back = await fetch_all(
            """SELECT count(*) AS n FROM actions_log
                WHERE at > $1 AND event = 'execute.superseded'""", since)
        returned = int(back[0]["n"]) if back else 0
        if returned:
            paragraphs.append(
                f"*Asked again*\n{returned} {_plural(returned, 'approval')} "
                f"came back to you for a fresh yes, because the action or "
                f"its details changed after you approved "
                f"{'it' if returned == 1 else 'them'}.")
    except Exception:                                   # noqa: BLE001
        log.warning("weekly: could not count superseded approvals")

    # --- the automation reporting on itself: read-backs, reconciles, ---
    # --- pauses, the outbox, missed runs, the restore drill          ---
    own_flags = 0
    try:
        checked = await checked_my_work(since, now)
        if checked:
            paragraphs.append(checked)
            own_flags = _flags_in(checked)
    except Exception:
        log.exception("weekly: the checked-my-work section failed")
        own_flags = 1
        paragraphs.append("*Checked my work*\nI couldn't put it together this "
                          "week, so it's unknown — not all clear.")

    # --- how the days felt, from the nightly reviews --------------------
    try:
        import json

        # reviews.day is a local calendar date (kernel/review.py builds it
        # from `datetime.now().astimezone().date()`), so the cutoff has to
        # be the LOCAL date of `since` -- `since.date()` is UTC-derived and
        # would miscount a review or two around local midnight.
        review_rows = await fetch_all(
            "SELECT score, went_wrong FROM reviews WHERE day >= $1",
            since.astimezone().date())
        scored = [r["score"] for r in review_rows if r["score"] is not None]
        if review_rows:
            from collections import Counter
            problems: Counter[str] = Counter()
            for r in review_rows:
                wrong = r["went_wrong"]
                if isinstance(wrong, str):
                    wrong = json.loads(wrong)
                problems.update(wrong or ())
            if scored:
                avg = sum(scored) / len(scored)
                # A day's score is the share of its reviewed items that went
                # well (kernel/review.py: well / (well + wrong)). A bare
                # "0.34" said nothing about what was measured.
                line = (f"On an average reviewed day, {avg:.0%} of the items "
                        f"reviewed went well ({len(scored)} "
                        f"{_plural(len(scored), 'day')} reviewed).")
            else:
                line = "No day this week scored well or badly enough to average."
            top = problems.most_common(1)
            if top:
                line += f' Most repeated problem: "{top[0][0]}" ({top[0][1]}x).'
            paragraphs.append("*How the days felt*\n" + line)
    except Exception:                                   # noqa: BLE001
        log.warning("weekly: could not read the daily reviews")

    # --- what has earned the offer to run on its own (the owner: "earn it") --
    try:
        from . import promotion
        cands = await promotion.candidates()
        if cands:
            paragraphs.append(promotion.render(cands))
    except Exception:                                   # noqa: BLE001
        log.warning("weekly: could not read the promotion candidates")

    # --- content: what posted itself (the owner, 2026-10-06: no cards, the
    # weekly is where posts are reported) -------------------------------
    try:
        from . import reels
        paragraphs.append(await reels.week_section(days))
    except Exception:
        log.exception("weekly: the content section failed")
        paragraphs.append("*Content this week*\nI could not read the posting "
                          "ledgers, so this week's count is UNKNOWN — not zero.")

    # --- the Academy's Shorts, each with its links and 7-day numbers (the owner,
    # 2026-10-12, the growth plan: "weekly 7-day performance log") ------
    try:
        from ..modules.academy import growth_log
        paragraphs.append(await growth_log.week_section(days))
    except Exception:
        log.exception("weekly: the Academy Shorts section failed")

    # --- money per reel: the Analyst's table, the Improver's decision ---
    try:
        from . import reel_money
        paragraphs.append(await reel_money.section(money, now=now, days=days))
    except Exception:
        log.exception("weekly: the money-per-reel section failed")
        paragraphs.append("*Money per reel*\nI could not put it together this "
                          "week, so every figure in it is UNKNOWN — not zero.")

    # --- Alinea: read from its emails; it trades on its own -------------
    try:
        from ..modules.markets import alinea
        paragraphs.append(await alinea.playlist_section(now))   # never raises
        paragraphs.append(await alinea.ideas_section(now))      # never raises
        paragraphs.append(await alinea.weekly_section(now))
    except Exception:
        log.exception("weekly: the Alinea section failed")
        paragraphs.append("*Alinea*\nI could not read its emails' records this "
                          "week, so every figure is UNKNOWN — not zero. Alinea "
                          "trades on its own; ATLAS only reads its emails.")

    # --- deals the owner checked (modules/realestate); it never raises ------
    try:
        from ..modules import realestate
        deals = await realestate.weekly_section(now)
        if "No deals checked this week." not in deals:    # quiet when idle
            paragraphs.append(deals)
    except Exception:
        log.exception("weekly: the deal-check section failed")

    # --- clip footage the retention run removed (kernel/privacy.py) ----
    try:
        gone = await fetch_all(
            """SELECT count(*) AS n, coalesce(sum(bytes), 0) AS b
                 FROM clip_sources WHERE deleted_at > $1::timestamptz""", since)
        removed = int(gone[0]["n"]) if gone else 0
        if removed:
            gb = int(gone[0]["b"] or 0) / 1e9
            paragraphs.append(
                f"*Clip footage*\nRemoved {removed} source "
                f"{_plural(removed, 'file')}, {gb:.1f} GB, once every clip cut "
                f"from {'it' if removed == 1 else 'them'} was posted or refused, "
                f"or none was waiting and it had sat past its retention window.")
    except Exception:                                   # noqa: BLE001
        log.warning("weekly: could not read the removed clip sources")
        paragraphs.append("*Clip footage*\nI could not read what footage was "
                          "removed this week, so that is UNKNOWN — not zero.")

    # --- what could not be measured ------------------------------------
    blind = sum(1 for r in rows if str(r["health"]) == Health.UNKNOWN)
    if blind:
        paragraphs.append(
            f"*Still blind*\n{blind} {_plural(blind, 'check')} couldn't run "
            f"at all, so I can't speak for those. Usually a credential I "
            f"don't have — `python -m atlas.cli connect` names each one.")

    # --- the headline, written last, from what the rest found ----------
    bad = len(still_wrong)
    if bad:
        headline = (f"{bad} {_plural(bad, 'thing')} "
                    f"{_plural(bad, 'needs', 'need')} you.")
    else:
        if own_flags:
            # The health checks were clean, but "Checked my work" is not: a
            # "Quiet week" above "1 did NOT take effect" would be a false calm.
            headline = (f"Nothing I watch broke, but {own_flags} "
                        f"{_plural(own_flags, 'thing')} in my own work "
                        f"{_plural(own_flags, 'needs', 'need')} a look.")
        elif not blind:
            headline = "Quiet week. Everything I watch was healthy throughout."
        else:
            headline = "Nothing broke."
        if blind:
            headline += (" Some of what I watch I still can't see, so treat "
                         "that as unknown rather than fine.")
    return Weekly(at=now, since=since, headline=headline,
                  paragraphs=paragraphs)


# ------------------------------------------------ the automation, on itself
#
# Read-backs (ATLAS_VERIFY_AFTER), cut-off runs looked up (ATLAS_RECONCILE),
# pauses, the outbox, missed runs and the restore drill -- one section, one
# line per fact, and only facts that are not zero. A part that could not be
# read says so: "couldn't read" is never "all clear". A switch that is off
# says so too, so an empty section never passes for a checked one.

# How long an ok `execute.finish` may go without its `verify.*` row before
# the read-back counts as cut short (a cancelled read-back writes nothing):
# the read-back's own timeout (verify.TIMEOUT_S, added at call time) + slack.
READBACK_GRACE = timedelta(minutes=10)
# The drill is a Sunday timer (ops/restore-drill); a week and a day of slack.
DRILL_STALE = timedelta(days=8)
# A window that ran this long after it was due was caught up, not on time.
LATE_RUN = timedelta(minutes=15)
_MAX_NAMED = 5


def _data(payload: Any) -> dict[str, Any]:
    """The `data` of an actions_log payload (stored as JSON text)."""
    import json
    try:
        parsed = json.loads(payload) if isinstance(payload, str) else payload
    except ValueError:
        return {}
    data = parsed.get("data", parsed) if isinstance(parsed, dict) else None
    return data if isinstance(data, dict) else {}


def _named(items: list[str]) -> str:
    more = len(items) - _MAX_NAMED
    return ", ".join(items[:_MAX_NAMED]) + (f", and {more} more" if more > 0 else "")


def _why(reason: Any, limit: int = 60) -> str:
    from ..modules._http import redact
    text = " ".join(redact(str(reason or "")).split())
    return text if len(text) <= limit else text[:limit - 1] + "…"


def _ago(delta: timedelta) -> str:
    if delta.days >= 1:
        return f"{delta.days}d ago"
    hours = int(delta.total_seconds() // 3600)
    return f"{hours}h ago" if hours >= 1 else "just now"


def _them(n: int) -> str:
    return "it" if n == 1 else "them"


async def _readback_lines(since: datetime, now: datetime) -> list[str]:
    from .executor import verify_after
    from .state import fetch_all
    from .verify import TIMEOUT_S

    rows = await fetch_all(
        """SELECT at, event, subject, payload FROM actions_log
            WHERE at > $1
              AND (event LIKE 'verify.%' OR event = 'execute.finish')
            ORDER BY at, id""", since)
    checks = [r for r in rows if str(r["event"]).startswith("verify.")]
    on = verify_after()
    if not checks:
        return [] if on else [
            "Read-back's off, so I didn't check whether what I did took effect."]
    confirmed = unsure = no_verifier = 0
    wrong: list[str] = []
    for r in checks:
        state, data = str(r["event"]).removeprefix("verify."), _data(r["payload"])
        if state == "verified":
            confirmed += 1
        elif state == "contradicted":
            why = _why(data.get("reason"))
            wrong.append(f"{r['subject']}" + (f" ({why})" if why else ""))
        else:
            unsure += 1
            no_verifier += str(data.get("reason") or "") == "no verifier"
    # An ok finish with no read-back after the grace was cut short. Only
    # finishes from the first read-back on: before it the switch was off,
    # and a week of those is not a week of failures.
    cut = 0
    if on:
        first, grace = checks[0]["at"], READBACK_GRACE + timedelta(seconds=TIMEOUT_S)
        waiting: dict[str, list[datetime]] = {}
        for r in rows:
            if r["at"] < first:
                continue
            if r["event"] == "execute.finish":
                if _data(r["payload"]).get("ok") is True:
                    waiting.setdefault(str(r["subject"]), []).append(r["at"])
            elif waiting.get(str(r["subject"])):
                waiting[str(r["subject"])].pop(0)
        cut = sum(1 for ats in waiting.values() for at in ats if now - at > grace)
    lines = []
    if confirmed:
        lines.append(f"{confirmed} {_plural(confirmed, 'action')} read back "
                     f"and confirmed.")
    if unsure + cut:
        extra = [(f"{no_verifier} {_plural(no_verifier, 'has', 'have')} no "
                  f"read-back built")] if no_verifier else []
        if cut:
            extra.append(f"{cut} never got one (cut short)")
        lines.append(f"{unsure + cut} I couldn't confirm either way"
                     + (f" — {', '.join(extra)}" if extra else "") + ".")
    if wrong:
        lines.append(f"{len(wrong)} did NOT take effect: {_named(wrong)}.")
    if not on:
        lines.append("Read-back's off now, so anything after that went unchecked.")
    return lines


async def _reconcile_lines(since: datetime) -> list[str]:
    from .approvals import reconcile_on
    from .state import fetch_all

    rows = await fetch_all(
        """SELECT event, subject FROM actions_log
            WHERE at > $1 AND (event LIKE 'reconcile.%'
                               OR event = 'execute.abandoned')
            ORDER BY at, id""", since)
    by: dict[str, list[str]] = {}
    for r in rows:
        by.setdefault(str(r["event"]), []).append(str(r["subject"]))
    done, failed = by.get("reconcile.done", []), by.get("reconcile.failed", [])
    human = by.get("reconcile.needs_human", [])
    parts = []
    if done:
        parts.append(f"{len(done)} took effect")
    if failed:
        parts.append(f"{len(failed)} didn't ({_named(failed)})")
    if human:
        parts.append(f"{len(human)} still unknown — check {_them(len(human))} "
                     f"by hand ({_named(human)})")
    lines = [f"Cut-off runs I looked up: {'; '.join(parts)}."] if parts else []
    left = len(by.get("execute.abandoned", [])) - len(done) - len(failed) - len(human)
    on = reconcile_on()
    if left > 0 and on:
        lines.append(f"{left} cut-off {_plural(left, 'run')} I didn't manage to "
                     f"look up — check {_them(left)} by hand.")
    elif left > 0:
        lines.append(f"{left} {_plural(left, 'run')} got cut off by a restart; "
                     f"reconcile's off, so I didn't look {_them(left)} up.")
    elif not on:
        lines.append("Reconcile's off — nothing got cut off this week anyway.")
    return lines


async def _pause_lines(now: datetime) -> list[str]:
    from .pause import ALL, SHADOW, active

    lines = []
    for p in await active():
        scope = p.scope.removeprefix(SHADOW)
        what = "Everything" if scope == ALL else scope
        state = "in shadow mode" if p.shadow else "paused"
        why = _why(p.reason, 80)
        lines.append(f"{what} {state} {_ago(now - p.paused_at)} by "
                     f"{p.paused_by}" + (f": {why}" if why else "") + ".")
    return lines


async def _outbox_lines(since: datetime) -> list[str]:
    from .state import fetch_all

    rows = await fetch_all(
        """SELECT status, action, count(*) AS n FROM outbox
            WHERE finished_at > $1 AND status IN ('failed', 'needs_human')
            GROUP BY status, action ORDER BY n DESC, action""", since)
    lines = []
    for status, said in (("failed", "failed for good"),
                         ("needs_human", "left for you to check by hand")):
        got = [(str(r["action"]), int(r["n"])) for r in rows
               if r["status"] == status]
        total = sum(n for _, n in got)
        if total:
            names = [a if n == 1 else f"{a} ×{n}" for a, n in got]
            lines.append(f"Outbox: {total} {_plural(total, 'send')} {said} — "
                         f"{_named(names)}.")
    return lines


async def _missed_lines(since: datetime) -> list[str]:
    from .state import fetch_all

    rows = await fetch_all(
        """SELECT job,
                  count(*) FILTER (WHERE status = 'skipped') AS skipped,
                  count(*) FILTER (WHERE status = 'done'
                                     AND scheduled_for IS NOT NULL
                                     AND claimed_at > scheduled_for + $2::interval)
                      AS late
             FROM schedule_runs
            WHERE (status = 'skipped' AND finished_at > $1)
               OR (status = 'done' AND claimed_at > $1)
            GROUP BY job ORDER BY job""", since, LATE_RUN)
    try:
        from .scheduler import POLICIES
    except Exception:                                   # noqa: BLE001
        POLICIES = {}
    parts = []
    for r in rows:
        policy = POLICIES.get(str(r["job"]))
        label = f" ({policy.missed})" if policy is not None else ""
        for n, said in ((int(r["skipped"]), "skipped"),
                        (int(r["late"]), "caught up late")):
            if n:
                parts.append(f"{r['job']} {said}" + (f" ×{n}" if n > 1 else "")
                             + label)
    return [f"Missed while I was down: {', '.join(parts)}."] if parts else []


async def _drill_line() -> tuple[str, bool]:
    """(the line, whether it is a warning). A drill that passed inside the
    week is not news on its own; anything else is."""
    import asyncio

    from ..modules import backups

    data, why = await asyncio.to_thread(backups._read, backups.DRILL)
    if data is None:
        if why and "does not exist" in why:
            return ("No restore drill on record — the backups aren't proven "
                    "to restore."), True
        return f"Couldn't read the restore drill result ({why}), so unknown.", True
    age = backups._age(data)
    if age is None:
        return "The restore drill result has no readable time, so unknown.", True
    if data.get("ok") is not True:
        return (f"Restore drill FAILED {_ago(age)} ({_why(data.get('dump'), 40)})"
                f" — the backups aren't proven to restore."), True
    if age > DRILL_STALE:
        return (f"Last restore drill passed, but {_ago(age)} — it should run "
                f"weekly."), True
    return f"Restore drill passed {_ago(age)}.", False


# Lines of "*Checked my work*" that are good news, not something to look at.
# A switch that is off is a setting he chose, said in the section, not a
# thing to look at.
_ALL_CLEAR = ("read back and confirmed.", "Restore drill passed ", "'s off")


def _flags_in(checked: str) -> int:
    """How many lines of the section are not plain good news."""
    return sum(1 for line in checked.splitlines()[1:]
               if line.startswith("• ")
               and not any(ok in line for ok in _ALL_CLEAR))


async def checked_my_work(since: datetime, now: datetime) -> str | None:
    """The weekly's "*Checked my work*", or None when there is nothing to say
    (every count zero, both switches on, the drill fresh and passing)."""
    lines: list[str] = []
    for name, part in (
            ("read-backs", lambda: _readback_lines(since, now)),
            ("cut-off run look-ups", lambda: _reconcile_lines(since)),
            ("pauses", lambda: _pause_lines(now)),
            ("outbox", lambda: _outbox_lines(since)),
            ("missed runs", lambda: _missed_lines(since))):
        try:
            lines.extend(await part())
        except Exception as exc:                        # noqa: BLE001
            log.warning("weekly: could not read the %s: %s", name, exc)
            lines.append(f"Couldn't read the {name}, so that's unknown — not zero.")
    try:
        drill, warn = await _drill_line()
        if warn or lines:
            lines.append(drill)
    except Exception as exc:                            # noqa: BLE001
        log.warning("weekly: could not read the restore drill: %s", exc)
        lines.append("Couldn't read the restore drill, so that's unknown.")
    if not lines:
        return None
    return "*Checked my work*\n" + "\n".join(f"• {line}" for line in lines)


async def send() -> Weekly:
    """Build it and put it where he reads things."""
    from .state import fetch_one

    # Same restart hole as the morning brief: the scheduler's weekly guard is
    # process memory, so a deploy on the weekly day re-sent it. The archive
    # is the durable record — one weekly per ISO week.
    monday = (datetime.now().astimezone() - timedelta(
        days=datetime.now().astimezone().weekday())).replace(
        hour=0, minute=0, second=0, microsecond=0)
    if await fetch_one("SELECT 1 AS x FROM reports WHERE kind = 'weekly' "
                       "AND at >= $1 LIMIT 1", monday):
        log.info("weekly summary already sent this week; not re-sending")
        return None  # type: ignore[return-value]
    from .comms import Outbound, notify

    # The reels Analyst, then the Improver (Plans/Money per reel.md): after
    # the once-a-week guard, so the mix is decided once, and the summary
    # shows the same numbers the decision was based on.
    money = None
    try:
        from . import reel_money
        money = await reel_money.week()
    except Exception:
        log.exception("weekly: the money-per-reel stage failed")
    weekly = await build(money=money)
    used = await notify(Outbound(
        title="This week", body=weekly.render(), severity=Severity.INFO,
        kind="digest", topic="brief"))
    log.info("weekly summary delivered via %s", used or "nothing")

    try:
        await store(weekly, delivered_via=",".join(used) or "undelivered")
    except Exception:
        # Keeping a copy is worth doing and not worth failing over -- but
        # this row IS the once-a-week guard above, so say it loudly.
        log.exception("could not store the weekly summary; the next restart "
                      "this week will send it again")
    return weekly


async def store(weekly: Weekly, *, delivered_via: str) -> int | None:
    """Keep the weekly, which is also what stops a second copy.

    It went through `brief.store`, which reads `brief.sections` -- a Weekly
    has none, so every store raised, nothing was kept, and every api restart
    that week sent "This week" again: six times into #mail-calender on
    2026-09-27 between 21:21 and 22:45 UTC, one per deploy.
    """
    import json

    from .state import fetch_one

    row = await fetch_one(
        """INSERT INTO reports (at, kind, title, body, sections, delivered_via)
           VALUES ($1,$2,$3,$4,$5,$6) RETURNING id""",
        weekly.at, "weekly",
        f"This week — {weekly.at.astimezone():%a %d %b}",
        weekly.render(), json.dumps([]), delivered_via)
    return row["id"] if row else None
