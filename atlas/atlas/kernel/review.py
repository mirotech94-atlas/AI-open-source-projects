"""The day, in plain words, once a night.

The morning brief is read every day and must be skimmable; the weekly
summary is read once a week and has to answer "what happened". This is the
third register: one evening, one score, three short lists. It exists so a
bad run of days is visible before it becomes a bad week — `weekly.build()`
reads the rows this writes and reports the average and the most repeated
problem.

Same discipline as `weekly.py`: nothing here is generated by a model. Every
line is assembled from a table this process already writes to for other
reasons — `observations`, `actions_log`, `proposals`, `findings` and
`decision_log`. A review that quietly invented a "went well" line would be
worse than no review, because it would look exactly like the real thing.

It also holds the page rubric (`score_page`, Phase 20): the same
discipline pointed at a built web page instead of a day. `agency.build_site`
generates up to five store variants and needs to rank them without asking a
model which one it likes -- so the rubric is a handful of deterministic
checks over the HTML, scored the way a day is (passed / checked), plus two
hard store checks that reject a page outright rather than lowering its
score: "no fabricated reviews" and "no payment form". A hard check is a
veto, not a weight: a page that invents a testimonial is not a slightly
worse page, it is one that must never be proposed.
"""
from __future__ import annotations

import logging
import re
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import date, datetime, time, timedelta
from html import unescape

from .contracts import Health, Severity

log = logging.getLogger("atlas.review")


@dataclass(frozen=True, slots=True)
class Review:
    day: date
    went_well: list[str]
    went_wrong: list[str]
    decisions: list[str]
    score: float | None


def _plural(n: int, one: str, many: str | None = None) -> str:
    return one if n == 1 else (many or one + "s")


def _local_day_bounds(day: date) -> tuple[datetime, datetime]:
    """Local midnight to local midnight the next day, as aware datetimes.

    `day` is a LOCAL calendar date. A bare `at::date = $1` filter truncates
    in whatever timezone the database SESSION happens to be in -- usually
    UTC -- not the caller's local one, so on a non-UTC host a large slice of
    the local day lands on the wrong side of the boundary (the bug
    `state.baseline()` and `privacy.run()` already had to work around, the
    first with `extract(... at time zone 'UTC')`, the second with
    `(at AT TIME ZONE 'UTC')::date`). Computing the bounds here, in local
    time, and filtering with a half-open range needs no cast at all and is
    correct regardless of what timezone Postgres runs in.

    `datetime.combine(...).astimezone()` on a naive datetime asks the
    platform for the correct local offset for THAT date, so this is right
    across a DST boundary too, not just for "today".
    """
    start = datetime.combine(day, time.min).astimezone()
    return start, start + timedelta(days=1)


async def build(day: date | None = None) -> Review:
    """Assemble one day from what was actually recorded, not from memory."""
    from .state import fetch_all

    target = day or datetime.now().astimezone().date()
    start, end = _local_day_bounds(target)
    went_well: list[str] = []
    went_wrong: list[str] = []

    # --- checks that recovered today -------------------------------------
    try:
        recovered = await fetch_all(
            """SELECT p.name AS property, c.name AS check_name
                 FROM observations o
                 JOIN checks c ON c.id = o.check_id
                 JOIN properties p ON p.id = c.property_id
                WHERE o.health = 'ok' AND o.at >= $1 AND o.at < $2
                  AND EXISTS (
                    SELECT 1 FROM observations bad
                     WHERE bad.check_id = o.check_id AND bad.at < o.at
                       AND bad.at >= $1 AND bad.at < $2
                       AND bad.health IN ('failing', 'degraded'))
                GROUP BY p.name, c.name
                ORDER BY p.name, c.name""", start, end)
    except Exception as exc:                            # noqa: BLE001
        log.warning("review: could not read recoveries: %s", exc)
        recovered = []
    for row in recovered:
        went_well.append(f"{row['property']}.{row['check_name']} recovered")

    # --- Tier 1 actions that ran on their own and succeeded ----------------
    # `approved_by` is null exactly when nothing needed to approve it: only
    # a Tier 1 action reaches the executor unattended (contracts.py, and
    # `executor.execute` refuses a Tier 2 one with no approver). A Tier 2
    # action always carries an approver, whether it came through a
    # `proposals` row or -- as `intent.py` does for a live phone/Slack
    # "yes, do it" -- straight past one, so it is never mistaken for this.
    try:
        acted = await fetch_all(
            """SELECT subject, count(*) AS n
                 FROM actions_log
                WHERE event = 'execute.finish' AND at >= $1 AND at < $2
                  AND (payload::jsonb -> 'data' ->> 'ok') = 'true'
                  AND (payload::jsonb -> 'data' ->> 'approved_by') IS NULL
                GROUP BY subject ORDER BY subject""", start, end)
    except Exception as exc:                            # noqa: BLE001
        log.warning("review: could not read the action log: %s", exc)
        acted = []
    for row in acted:
        n = int(row["n"])
        went_well.append(f"{row['subject']} ran on its own, "
                          f"{n} {_plural(n, 'time')}")

    # --- Tier 2 actions approved live, outside the proposal flow -----------
    # `intent.py` can approve and execute an ask-tier action in the same
    # breath and never writes a `proposals` row for it. Those still carry
    # `approved_by`, so they are told apart from a Tier 1 action above; the
    # NOT IN keeps one that DID go through an approved-and-executed
    # proposal from being counted twice, once here and once below.
    try:
        approved_live = await fetch_all(
            """SELECT subject,
                      (payload::jsonb -> 'data' ->> 'approved_by') AS approved_by
                 FROM actions_log
                WHERE event = 'execute.finish' AND at >= $1 AND at < $2
                  AND (payload::jsonb -> 'data' ->> 'ok') = 'true'
                  AND (payload::jsonb -> 'data' ->> 'approved_by') IS NOT NULL
                  AND subject NOT IN (
                    SELECT action FROM proposals
                     WHERE status = 'executed' AND decided_at >= $1 AND decided_at < $2)
                ORDER BY subject""", start, end)
    except Exception as exc:                            # noqa: BLE001
        log.warning("review: could not read live approvals: %s", exc)
        approved_live = []
    for row in approved_live:
        channel = (row["approved_by"] or "").split(":", 1)[0] or "you"
        went_well.append(f"{row['subject']} — on your word from {channel}")

    # --- proposals approved and carried out through -------------------------
    try:
        done = await fetch_all(
            """SELECT action, decided_at FROM proposals
                WHERE status = 'executed' AND decided_at >= $1 AND decided_at < $2
                ORDER BY decided_at""", start, end)
    except Exception as exc:                            # noqa: BLE001
        log.warning("review: could not read proposals: %s", exc)
        done = []
    for row in done:
        went_well.append(f"{row['action']} — approved and done")

    # --- findings still open at the end of the day --------------------------
    try:
        latest = await fetch_all(
            """SELECT DISTINCT ON (f.check_key)
                      f.check_key, f.health
                 FROM findings f
                WHERE f.at >= $1 AND f.at < $2
                ORDER BY f.check_key, f.at DESC""", start, end)
    except Exception as exc:                            # noqa: BLE001
        log.warning("review: could not read findings: %s", exc)
        latest = []
    for row in latest:
        if str(row["health"]) in (Health.FAILING, Health.DEGRADED):
            # The check's name and health, never its detail: every
            # went_wrong line becomes a lesson in each agent's system
            # prompt (lessons.from_review), and a detail quotes whatever
            # the collector saw -- a room name, a sender, a subject.
            went_wrong.append(f"{row['check_key']} — still {row['health']}")

    # --- actions that failed -------------------------------------------
    try:
        failed = await fetch_all(
            """SELECT subject, count(*) AS n
                 FROM actions_log
                WHERE at >= $1 AND at < $2
                  AND (event = 'execute.error'
                       OR (event = 'execute.finish'
                           AND (payload::jsonb -> 'data' ->> 'ok') = 'false'))
                GROUP BY subject ORDER BY subject""", start, end)
    except Exception as exc:                            # noqa: BLE001
        log.warning("review: could not read failed actions: %s", exc)
        failed = []
    for row in failed:
        n = int(row["n"])
        went_wrong.append(f"{row['subject']} failed, {n} {_plural(n, 'time')}")

    # --- proposals that expired unanswered -------------------------------
    try:
        expired = await fetch_all(
            """SELECT action FROM proposals
                WHERE status = 'expired' AND expires_at >= $1 AND expires_at < $2
                ORDER BY expires_at""", start, end)
    except Exception as exc:                            # noqa: BLE001
        log.warning("review: could not read expired proposals: %s", exc)
        expired = []
    for row in expired:
        went_wrong.append(f"{row['action']} — expired unanswered")

    # --- what was decided today, whichever way it went ----------------------
    try:
        decided = await fetch_all(
            """SELECT module, action, outcome FROM decision_log
                WHERE at >= $1 AND at < $2
                ORDER BY at""", start, end)
    except Exception as exc:                            # noqa: BLE001
        log.warning("review: could not read the decision log: %s", exc)
        decided = []
    decisions = [f"{row['module']}.{row['action']}: {row['outcome']}"
                 for row in decided]

    well, wrong = len(went_well), len(went_wrong)
    score = well / (well + wrong) if (well + wrong) else None

    return Review(day=target, went_well=went_well, went_wrong=went_wrong,
                  decisions=decisions, score=score)


def render(r: Review) -> str:
    header = f"*Tonight* — {r.day:%-d %B}"
    if not r.went_well and not r.went_wrong and not r.decisions:
        return f"{header}\nQuiet day: nothing broke and nothing was decided."

    parts = [header]
    parts.append("*Went well*\n" + ("\n".join(f"• {x}" for x in r.went_well)
                                    if r.went_well else "  Nothing to point to."))
    parts.append("*Went wrong*\n" + ("\n".join(f"• {x}" for x in r.went_wrong)
                                     if r.went_wrong else "  Nothing."))
    parts.append("*Decided*\n" + ("\n".join(f"• {x}" for x in r.decisions)
                                  if r.decisions else "  Nothing waited on you."))
    if r.score is not None:
        parts.append(f"Score: {r.score:.2f}")
    return "\n\n".join(parts)


async def send(day: date | None = None) -> Review:
    """Build it, deliver it, and keep a copy. Called by the scheduler at
    REVIEW_HOUR local time."""
    import json

    from .comms import Outbound, notify
    from .state import execute_sql, fetch_one

    review = await build(day)
    rendered = render(review)
    used = await notify(Outbound(
        title=f"Tonight — {review.day:%a %d %b}", body=rendered,
        severity=Severity.INFO, kind="digest"))
    log.info("daily review delivered via %s", used or "nothing")

    try:
        saved = await fetch_one(
            """INSERT INTO reviews (day, went_well, went_wrong, decisions, score)
                    VALUES ($1,$2,$3,$4,$5)
               ON CONFLICT (day) DO UPDATE
                      SET went_well = EXCLUDED.went_well,
                          went_wrong = EXCLUDED.went_wrong,
                          decisions = EXCLUDED.decisions,
                          score = EXCLUDED.score
               RETURNING id""",
            review.day, json.dumps(review.went_well),
            json.dumps(review.went_wrong), json.dumps(review.decisions),
            review.score)
        report = await fetch_one(
            """INSERT INTO reports (kind, title, body, delivered_via)
                    VALUES ('review', $1, $2, $3) RETURNING id""",
            f"Tonight — {review.day:%a %d %b}", rendered,
            ",".join(used) or "undelivered")
        if saved and report:
            await execute_sql(
                "UPDATE reviews SET report_id = $2 WHERE id = $1",
                saved["id"], report["id"])
    except Exception:                                    # noqa: BLE001
        # A day whose review could not be stored is worse than one whose
        # review was never delivered -- but it was still delivered, so this
        # is not worth failing the send over.
        log.warning("could not store the daily review")

    # Nightly, and after the row is written: every "went wrong" line becomes a
    # lesson, deduplicated, so the same problem three nights running is one
    # lesson with times = 3 rather than three notes nobody reads. `lessons`
    # reads the stored review back rather than this object, which is what
    # keeps it from importing this file in return.
    from . import lessons
    learned = await lessons.from_review(review.day)
    if learned:
        log.info("%d lesson(s) from the review of %s", learned, review.day)
    # The same failure recognised across nights and parameters, and said
    # once when it becomes a pattern (kernel/ledger.py). A report only.
    try:
        from . import ledger
        await ledger.nightly()
    except Exception:
        log.exception("the ledger pass failed; the review is unaffected")
    return review


# --------------------------------------------------------------- page rubric
#
# Every check reads the raw HTML exactly as it will be served. That matters
# for the two hard checks: `agency.build` escapes model copy, so a headline
# of "<form>" lands as `&lt;form` -- text a visitor reads, not a form a
# visitor can type a card into -- and these patterns only ever match real
# markup.

_TAG = re.compile(r"<[^>]+>")
_SPACE = re.compile(r"\s+")
_TITLE = re.compile(r"<title[^>]*>(.*?)</title>", re.IGNORECASE | re.DOTALL)
_H1 = re.compile(r"<h1[^>]*>(.*?)</h1>", re.IGNORECASE | re.DOTALL)
_IMG_ALT = re.compile(r"<img\b[^>]*\balt\s*=\s*\"([^\"]*)\"", re.IGNORECASE)
_HERO = re.compile(r'<section[^>]*id="hero"[^>]*>(.*?)</section>',
                   re.IGNORECASE | re.DOTALL)
_PARA = re.compile(r"<p[^>]*>(.*?)</p>", re.IGNORECASE | re.DOTALL)
_SECTION = re.compile(r"<section\b[^>]*>(.*?)</section>", re.IGNORECASE | re.DOTALL)
_HEADING = re.compile(r"<h[1-6][^>]*>.*?</h[1-6]>", re.IGNORECASE | re.DOTALL)
_CONTACT = re.compile(r'id="how-to-order"|href="(?:tel|mailto):', re.IGNORECASE)
_PRESSURE = re.compile(
    r"\b(?:today only|limited time|hurry|act now|only \d+ left|while stocks? last|"
    r"selling fast|last chance|ends (?:tonight|soon)|don'?t miss out)\b",
    re.IGNORECASE)

# "No payment form": a real <form> element whose markup mentions a card or a
# payment, or any input asking for card details wherever it sits.
_FORM = re.compile(r"<form\b.*?(?:</form>|\Z)", re.IGNORECASE | re.DOTALL)
_PAYMENT_WORDS = re.compile(
    r"card|payment|checkout|cvv|cvc|billing|iban|expir", re.IGNORECASE)
_CARD_INPUT = re.compile(
    r"<input\b[^>]*(?:cc-|card|cvv|cvc|autocomplete\s*=\s*\"cc)", re.IGNORECASE)

# "No fabricated reviews": the shapes a testimonial or a rating takes.
_BLOCKQUOTE = re.compile(r"<blockquote\b[^>]*>(.*?)</blockquote>",
                         re.IGNORECASE | re.DOTALL)
_FOOTER = re.compile(r"<footer\b.*?</footer>", re.IGNORECASE | re.DOTALL)
_STARS = re.compile(r"[★☆]|&#9733;|&#x2605;|&starf;")
_RATING = re.compile(r"\b\d(?:\.\d)?\s*(?:/\s*5\b|out of 5\b|-?\s*stars?\b)",
                     re.IGNORECASE)
_REVIEWS_SECTION = re.compile(r'<section[^>]*id="reviews"[^>]*>(.*?)</section>',
                              re.IGNORECASE | re.DOTALL)
_TESTIMONIAL_CLASS = re.compile(r'class="[^"]*\b(?:testimonial|review-item|rating)\b',
                                re.IGNORECASE)

NO_FABRICATED_REVIEWS = "no fabricated reviews"
NO_PAYMENT_FORM = "no payment form"


@dataclass(frozen=True, slots=True)
class RubricCheck:
    name: str
    passed: bool
    hard: bool = False          # a failed hard check rejects the page outright
    detail: str = ""


@dataclass(frozen=True, slots=True)
class PageScore:
    score: float | None         # passed / checked over the soft checks
    checks: tuple[RubricCheck, ...]

    @property
    def rejected(self) -> bool:
        return any(c.hard and not c.passed for c in self.checks)

    @property
    def failed(self) -> list[str]:
        return [c.name for c in self.checks if not c.passed]


def _text(fragment: str) -> str:
    return _SPACE.sub(" ", unescape(_TAG.sub(" ", fragment or ""))).strip()


def _no_payment_form(html: str) -> RubricCheck:
    for form in _FORM.findall(html):
        if _PAYMENT_WORDS.search(form):
            return RubricCheck(NO_PAYMENT_FORM, False, True,
                               "a <form> on the page asks for a card or a payment")
    if _CARD_INPUT.search(html):
        return RubricCheck(NO_PAYMENT_FORM, False, True,
                           "an <input> on the page asks for card details")
    return RubricCheck(NO_PAYMENT_FORM, True, True)


def _no_fabricated_reviews(html: str, client_reviews: Sequence[str] | None) -> RubricCheck:
    """A testimonial is only allowed when it is one the client supplied,
    word for word. With no client file there must be no testimonial shape
    on the page at all -- no quote, no star, no rating -- and the neutral
    "reviews are on their way" line passes because it is none of those."""
    supplied = {_text(r) for r in (client_reviews or ()) if _text(r)}
    quotes = [_text(_FOOTER.sub(" ", q)) for q in _BLOCKQUOTE.findall(html)]
    invented = [q for q in quotes if q not in supplied]
    if invented:
        return RubricCheck(NO_FABRICATED_REVIEWS, False, True,
                           f"a testimonial no client supplied: {invented[0][:60]!r}")
    if _TESTIMONIAL_CLASS.search(html) and not supplied:
        return RubricCheck(NO_FABRICATED_REVIEWS, False, True,
                           "a testimonial block with no client file behind it")
    # A star or a score inside the reviews section is a rating someone has
    # to have given. Elsewhere a figure like "5-star" can be the client's own
    # product description, which `agency.build` has already checked copy
    # against -- so this looks where a rating would pose as a review.
    # Every quote left at this point is one the client supplied, so their
    # own words ("five stars from me") are taken out before looking.
    reviews = _REVIEWS_SECTION.search(html)
    block = _BLOCKQUOTE.sub(" ", reviews.group(1)) if reviews else ""
    if block and (_STARS.search(block) or _RATING.search(_text(block))):
        return RubricCheck(NO_FABRICATED_REVIEWS, False, True,
                           "a star rating in the reviews section")
    return RubricCheck(NO_FABRICATED_REVIEWS, True, True)


def score_page(html: str, *, store: bool = False,
               client_reviews: Sequence[str] | None = None) -> PageScore:
    """Score one built page. Deterministic: the same HTML always gets the
    same score, so ranking variants never depends on which model is up.

    Soft checks (each worth the same): a title, one short headline (2-12
    words), a hero image with alt text, a supporting line in the hero, a
    way to order or get in touch, every section carrying content beyond its
    heading, and no pressure copy ("today only", "only 3 left"). With
    `store=True`, the two hard checks run as well; `client_reviews` is the
    text of the reviews the client supplied, when there is a file."""
    checks: list[RubricCheck] = []

    title = _TITLE.search(html)
    checks.append(RubricCheck("has a title", bool(title and _text(title.group(1)))))

    h1 = _H1.search(html)
    words = len(_text(h1.group(1)).split()) if h1 else 0
    checks.append(RubricCheck("one short headline", 2 <= words <= 12,
                              detail=f"{words} words"))

    alts = [a for a in _IMG_ALT.findall(html) if a.strip()]
    checks.append(RubricCheck("an image with alt text", bool(alts)))

    hero = _HERO.search(html)
    lines = [_text(p) for p in _PARA.findall(hero.group(1))] if hero else []
    checks.append(RubricCheck("a supporting line under the headline", any(lines)))

    checks.append(RubricCheck("a way to order or get in touch",
                              bool(_CONTACT.search(html))))

    sections = _SECTION.findall(html)
    empty = [s for s in sections if not _text(_HEADING.sub(" ", s))]
    checks.append(RubricCheck("every section has content", bool(sections) and not empty,
                              detail=f"{len(empty)} empty"))

    checks.append(RubricCheck("no pressure copy", not _PRESSURE.search(_text(html))))

    soft = list(checks)
    if store:
        checks.append(_no_fabricated_reviews(html, client_reviews))
        checks.append(_no_payment_form(html))

    passed = sum(1 for c in soft if c.passed)
    score = passed / len(soft) if soft else None
    return PageScore(score=score, checks=tuple(checks))
