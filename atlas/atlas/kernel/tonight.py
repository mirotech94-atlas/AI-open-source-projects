"""Goodnight (15.4): what is actually scheduled, said once, then quiet.

Every sentence here comes from a table or from a module's own agenda:
the night-shift jobs queued or running, research reports still queued, the
hours the scheduler really runs the model tournament and the morning brief,
the first thing on the agenda when he wakes, and the proposals still
waiting on him. Nothing is generated by a model and nothing is promised
that is not on a schedule -- a goodnight that invented a task to sound busy
would look exactly like a real one, which is why it must never happen.

The only promise made about the future is the prep card, and only for a
calendar event while the calendar module is loaded -- that is the one thing
`calendar._prep_signals` actually does, 30 minutes before every meeting. A
deadline gets no such promise. Jobs are named by status ("queued",
"running"), never as "ready by morning": nothing guarantees when they end.

A table that cannot be read is said to be unreadable, never skipped: an
empty sentence and a failed read must not sound the same (invariant 7). A
module agenda that does not answer within `AGENDA_TIMEOUT_S` is unreadable
too. The brief "goes out" only when a channel would take it; otherwise it
"will be on the dashboard", which is where `brief.send()` stores it.

Reads only. Nothing here imports the executor or a model.
"""
from __future__ import annotations

import asyncio
import logging
from datetime import date, datetime, timedelta

from .contracts import AgendaItem
from .registry import REGISTRY
from .state import fetch_all, fetch_one

log = logging.getLogger("atlas.tonight")

# Before this local hour, "the morning" is today's, not tomorrow's: he says
# goodnight after midnight as often as before it.
NIGHT_ENDS_HOUR = 5
# How far ahead the agenda is read. Enough for tomorrow from any hour.
AGENDA_WINDOW = timedelta(hours=36)
# One hung agenda must not hang the goodnight: past this it is said as
# unreadable, like any other failure.
AGENDA_TIMEOUT_S = 5.0
MAX_NAMED = 3
MAX_TASK_CHARS = 80
PREP_PROMISE = "I'll have a prep card 30 minutes before."


def _now() -> datetime:
    """Local, aware. A seam so a test can put the clock at 22:40 or 01:15."""
    return datetime.now().astimezone()


def _hhmm(at: datetime) -> str:
    return at.astimezone().strftime("%H:%M")


def _plural(n: int, one: str, many: str) -> str:
    return one if n == 1 else many


def _names(items: list[str]) -> str:
    """At most MAX_NAMED, each cut short, "a, b and c" / "... and N more"."""
    shown = [t if len(t) <= MAX_TASK_CHARS else t[: MAX_TASK_CHARS - 1] + "…"
             for t in items[:MAX_NAMED]]
    rest = len(items) - len(shown)
    if rest:
        return ", ".join(shown) + f" and {rest} more"
    if len(shown) == 1:
        return shown[0]
    return ", ".join(shown[:-1]) + " and " + shown[-1]


def _wake_day(now: datetime) -> date:
    """The day he wakes into."""
    return now.date() if now.hour < NIGHT_ENDS_HOUR else now.date() + timedelta(days=1)


def _day_word(day: date, now: datetime) -> str:
    if day == now.date():
        return "today" if now.hour < NIGHT_ENDS_HOUR else "tonight"
    if day == now.date() + timedelta(days=1):
        return "tomorrow"
    return day.strftime("%A")


async def _night_shift() -> str:
    try:
        rows = await fetch_all(
            """SELECT task, status FROM nightshift_jobs
               WHERE status IN ('queued', 'running') ORDER BY at""")
    except Exception as exc:                            # noqa: BLE001
        log.warning("tonight: night-shift queue unreadable: %s", exc)
        return "I couldn't read the night-shift queue."
    running = [str(r["task"]).strip() for r in rows or [] if r["status"] == "running"]
    queued = [str(r["task"]).strip() for r in rows or [] if r["status"] == "queued"]
    out = []
    if running:
        out.append(f"The night shift is running {_names(running)}.")
    if queued:
        out.append(f"Queued for the night shift: {_names(queued)}.")
    return " ".join(out)


async def _research() -> str:
    try:
        rows = await fetch_all(
            "SELECT question FROM research_reports WHERE status = 'queued' ORDER BY at")
    except Exception as exc:                            # noqa: BLE001
        log.warning("tonight: research queue unreadable: %s", exc)
        return "I couldn't read the research queue."
    n = len(rows or [])
    if not n:
        return ""
    return f"{n} research {_plural(n, 'report is', 'reports are')} queued."


async def _brief_channel() -> bool:
    """Whether anything would deliver the brief. `brief.send()` runs and
    stores it either way, but "goes out" is only true when a channel is
    listening at its severity -- the router's own answer, not a guess."""
    from .comms import candidates
    from .contracts import Severity

    try:
        return bool(await candidates(Severity.NORMAL))
    except Exception as exc:                            # noqa: BLE001
        log.warning("tonight: channel availability unreadable: %s", exc)
        return False


async def _schedule() -> str:
    # Lazy: the scheduler imports half the kernel. The hours are its own
    # parsers, so a bad BRIEF_HOUR is read here exactly as it is there.
    from .scheduler import _brief_hour, _tournament_hour

    brief = (f"the morning brief goes out at {_brief_hour():02d}:00"
             if await _brief_channel()
             else f"the morning brief will be on the dashboard at {_brief_hour():02d}:00")
    return f"The model tournament runs at {_tournament_hour():02d}:00 and {brief}."


async def _agenda(now: datetime) -> tuple[list[AgendaItem], list[str]]:
    """Every loaded module's agenda, and the names of those that failed --
    `brief.agenda_items` swallows a failure, and here a failed calendar
    must not sound like an empty one."""
    names = list(REGISTRY.modules)

    async def one(name: str) -> list[AgendaItem] | None:
        try:
            got = await asyncio.wait_for(
                REGISTRY.modules[name].agenda(AGENDA_WINDOW), AGENDA_TIMEOUT_S)
        except Exception as exc:                        # noqa: BLE001
            log.warning("tonight: %s agenda unreadable: %s", name, exc)
            return None
        return [AgendaItem(when=i.when, title=i.title, kind=i.kind, detail=i.detail,
                           minutes=i.minutes, source=i.source or name)
                for i in got or ()]

    results = await asyncio.gather(*(one(n) for n in names))
    items: list[AgendaItem] = []
    failed: list[str] = []
    for name, got in zip(names, results, strict=True):
        if got is None:
            failed.append(name)
        else:
            items.extend(got)
    items.sort(key=lambda i: i.when)
    return items, failed


async def _first_up(now: datetime) -> str:
    items, failed = await _agenda(now)
    wake = _wake_day(now)
    ahead = [i for i in items if i.when >= now and i.when.astimezone().date() <= wake]
    out = []
    if ahead:
        first = ahead[0]
        when = first.when.astimezone()
        day = _day_word(when.date(), now)
        title = first.title.strip() or "(no title)"
        if first.kind == "event":
            line = f"First on the agenda: {title}, {day} at {_hhmm(when)}."
            if first.source == "calendar" and "calendar" in REGISTRY.modules:
                line += f" {PREP_PROMISE}"
        else:
            line = f"First on the agenda: {title}, due {day} at {_hhmm(when)}."
        out.append(line)
    if failed:
        out.append(f"I couldn't read the agenda from {_names(failed)}.")
    elif not ahead:
        if "calendar" not in REGISTRY.modules:
            out.append("No calendar is connected, so I can't see "
                       f"{_day_word(wake, now)}'s meetings.")
        else:
            out.append(f"Nothing is on the agenda for {_day_word(wake, now)}.")
    return " ".join(out)


async def _proposals() -> str:
    try:
        row = await fetch_one(
            """SELECT count(*) AS n FROM proposals
               WHERE status = 'pending' AND expires_at > now()""")
    except Exception as exc:                            # noqa: BLE001
        log.warning("tonight: proposals unreadable: %s", exc)
        return "I couldn't read the proposals waiting on you."
    n = int(row["n"]) if row else 0
    if not n:
        return ""
    if n == 1:
        return "1 proposal is waiting; it expires, it never runs."
    return f"{n} proposals are waiting; they expire, they never run."


async def build() -> str:
    """The goodnight hand-off: tables and agendas only, ending "Rest up."."""
    now = _now()
    parts = [f"Goodnight. As of {_hhmm(now)}:"]
    parts.append(await _night_shift())
    parts.append(await _research())
    parts.append(await _schedule())
    parts.append(await _first_up(now))
    parts.append(await _proposals())
    parts.append("Rest up.")
    return " ".join(p for p in parts if p)
